PRAGMA foreign_keys = ON;

-- ---------- Завдання 1. printf() для числової колонки ----------
-- Числова колонка фактової таблиці: sales.price
SELECT id,
       price                         AS raw_price,
       printf('%.2f грн', price)     AS formatted_price
FROM sales;
-- Результат (10 рядків), приклад:
--   1 | 650000.0 | 650000.00 грн
--   2 | 485000.0 | 485000.00 грн
--   ...
--  10 | 490000.0 | 490000.00 грн

-- ---------- Завдання 2. printf() з вирівнюванням ----------
SELECT id,
       printf('%05d', id)            AS id_padded,
       printf('%12.2f', price)       AS price_aligned
FROM sales;
-- Результат, приклад:
--   1 | 00001 |    650000.00
--   2 | 00002 |    485000.00
--  10 | 00010 |    490000.00

-- ---------- Завдання 3. Зсув дати відносно наявної ----------
-- +14 днів від дати продажу = остання дата, коли можна повернути/обміняти авто
SELECT id,
       sale_date,
       date(sale_date, '+14 days')   AS return_deadline
FROM sales;
-- Результат, приклад:
--   1 | 2026-02-10 | 2026-02-24
--   2 | 2026-02-18 | 2026-03-04   (перехід через кінець місяця опрацьовано)
--  10 | 2026-06-25 | 2026-07-09

-- ---------- Завдання 4. strftime() + GROUP BY ----------
SELECT strftime('%Y-%m', sale_date)  AS ym,
       COUNT(*)                      AS sales_count
FROM sales
GROUP BY ym
ORDER BY ym;
-- Результат:
--   2026-02 | 2
--   2026-03 | 2
--   2026-04 | 2
--   2026-05 | 2
--   2026-06 | 2

-- ---------- Завдання 5. Свідома помилка з некоректною датою ----------
SELECT strftime('%Y', 'not-a-date') AS result;
-- Результат: NULL (помилки немає)

SELECT date('not-a-date') AS result;
-- Результат: NULL (помилки немає)

-- Колонка, яка дат не містить:
SELECT id, payment_method, strftime('%Y', payment_method) AS result
FROM sales
LIMIT 3;
-- Результат:
--   1 | готівка       | NULL
--   2 | кредит        | NULL
--   3 | безготівковий | NULL
